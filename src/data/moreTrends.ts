// Helper to generate trend history points
function genHistory(baseValue: number, trendMultiplier: number, volatility: number = 4) {
  const points = [];
  const today = new Date('2026-10-18');
  for (let i = 29; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    const progress = (30 - i) / 30;
    const noise = Math.sin(i * 1.3) * volatility;
    const value = Math.max(5, Math.min(100, Math.round(baseValue + progress * trendMultiplier + noise)));
    points.push({ date: dateStr, value });
  }
  return points;
}

